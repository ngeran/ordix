const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, el };

// ============================================================
// SECTION: Locale store & translation hook
// ============================================================

interface LocaleState {
  /** Language on screen right now. */
  locale: Locale;
  /** The EN/EL switch: shows the language and remembers the choice. */
  setLocale: (locale: Locale) => void;
}

// ============================================================
// SECTION: Locale persistence — a cookie, not localStorage
// ------------------------------------------------------------
// The device's choice lives in the "ordix-locale" cookie so the
// SERVER can render the right language too (root layout →
// resolveLocale). Server and client therefore agree from the very
// first paint: no flash, and no hydration mismatch in Suspense-
// streamed parts of a page.
// ============================================================

function readLocaleCookie(): Locale | null {
  if (typeof document === "undefined") return null;
  const match = document.cookie.match(/(?:^|;\s*)ordix-locale=(en|el)(?:;|$)/);
  return (match?.[1] as Locale | undefined) ?? null;
}

export const useLocaleStore = create<LocaleState>()((set) => ({
  locale: "el",
  setLocale: (locale) => {
    document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000; samesite=lax`;
    set({ locale });
  },
}));

// ============================================================
// SECTION: Settings-driven locale (admin → Settings → Language)
// ------------------------------------------------------------
//   resolveLocale — the language to show: the device's saved
//                   choice when switching is allowed, otherwise
//                   (or with no choice yet) the business default
//   seedLocale    — first render, server + client: start in it
//   applyLocale   — client, when settings change (admin saved)
// A lock never touches the cookie, so unlocking restores each
// device's own choice.
// ============================================================

export function seedLocale(locale: Locale): void {
  if (useLocaleStore.getState().locale !== locale) {
    useLocaleStore.setState({ locale });
  }
}

export function applyLocale(rules: LanguageRules): void {
  seedLocale(resolveLocale(rules, readLocaleCookie()));
}

/**
 * Translation hook: `const t = useT(); t("pos.placeOrder")`.
 * Supports `{placeholder}` interpolation via the optional vars map.
 */
export function useT() {
  const locale = useLocaleStore((state) => state.locale);
  return (key: MessageKey, vars?: Record<string, string | number>): string =>
    translate(key, vars);
}

// ============================================================
// SECTION: Non-React translation access
// ------------------------------------------------------------
// For code outside components (outbox flush toasts, service
// helpers) that still needs localized strings.
// ============================================================

export function getLocale(): Locale {
  return useLocaleStore.getState().locale;
}

export function translate(
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const locale = getLocale();
  let text: string = dictionaries[locale][key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Reactive locale for components that need it directly (dates etc.). */
export function useLocale(): Locale {
  return useLocaleStore((state) => state.locale);
}
